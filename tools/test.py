from playwright.sync_api import sync_playwright
import json
B='http://localhost:8765/xiangsheng-tree/'
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=b.new_page(viewport={'width':1440,'height':900})
    pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.goto(B); pg.wait_for_function("document.querySelector('#stat').textContent.length>0",timeout=30000)
    pg.wait_for_timeout(1500)
    print('stat',pg.inner_text('#stat'))
    pg.screenshot(path='shots/01-network.png')
    pg.fill('#q','郭德纲'); pg.wait_for_timeout(300)
    print('suggest',pg.inner_text('#suggest')[:120])
    pg.keyboard.press('Enter'); pg.wait_for_timeout(1500)
    print('panel',pg.inner_text('#panel')[:200].replace('\n',' | '))
    pg.screenshot(path='shots/02-search-guodegang.png')
    pg.select_option('#mode','ego'); pg.wait_for_timeout(2500)
    print('ego',pg.inner_text('#stat'))
    pg.screenshot(path='shots/03-ego-guodegang.png')
    pg.fill('#q','马三立'); pg.wait_for_timeout(300); pg.keyboard.press('Enter'); pg.wait_for_timeout(2500)
    print('panel2',pg.inner_text('#panel')[:300].replace('\n',' | '))
    pg.screenshot(path='shots/04-ego-masanli.png')
    pg.goto(B+'#people'); pg.wait_for_timeout(1000); pg.fill('#pq','侯'); pg.wait_for_timeout(400); print('people',pg.inner_text('#pcount'))
    pg.screenshot(path='shots/05-people-table.png')
    pg.goto(B+'#relations'); pg.wait_for_timeout(1000); pg.select_option('#rtype','kin'); pg.wait_for_timeout(400); print('rels',pg.inner_text('#rcount'))
    pg.screenshot(path='shots/06-relations-kin.png')
    pg.goto(B+'#about'); pg.wait_for_timeout(800); pg.screenshot(path='shots/07-about.png',full_page=True)
    m=b.new_page(viewport={'width':390,'height':844},device_scale_factor=2,is_mobile=True,has_touch=True)
    m.goto(B+'#graph/'+[x for x in json.load(open('site/data/people.json')) if x['name']=='侯宝林'][0]['id']); m.wait_for_timeout(3000)
    m.screenshot(path='shots/08-mobile-houbaolin.png',full_page=True)
    b.close()
print('ERRORS',errs)
